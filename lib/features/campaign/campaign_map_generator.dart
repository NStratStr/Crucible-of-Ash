  /// Generates the DAG expedition map for the specified chapter.
  static List<CampaignNode> generateCampaignForChapter(int chapter) {
    switch (chapter) {
      case 2:
        return _generateChapter2();
      case 3:
        return _generateChapter3();
      case 1:
      default:
        return _generateChapter1();
    }
  }

